const { test } = require('node:test'),
  assert = require('node:assert/strict'),
  fs = require('node:fs'),
  path = require('node:path');
const output = path.resolve(__dirname, '../node_modules/.cache/link-tree-test.cjs');
fs.mkdirSync(path.dirname(output), { recursive: true });
require('esbuild').buildSync({
  entryPoints: [path.resolve(__dirname, '../client/link-tree.js')],
  outfile: output,
  bundle: true,
  platform: 'node',
  format: 'cjs',
});
const {
  buildLinkTree,
  filterLinkTree,
  pageTarget,
  findLinkedPage,
  openLinkBranches,
  validateLink,
} = require(output);
const collection = {
  id: 'docs:default',
  root: 'manual',
  type: 'docs',
  version: 'current',
  pluginId: 'default',
};
const pages = [
  {
    collection: collection.id,
    path: 'manual/start.md',
    id: 'start',
    title: 'Welcome',
    url: '/help/start',
  },
  {
    collection: collection.id,
    path: 'manual/guide/setup.mdx',
    id: 'guide/setup',
    title: 'Installation',
    url: '/help/install',
  },
  {
    collection: collection.id,
    path: 'manual/extra.md',
    id: 'extra',
    title: 'Extra information',
    url: '/help/extra',
  },
  { collection: 'pages:default', path: 'web/pages/index.jsx', title: 'index', url: '/help/' },
  {
    collection: collection.id,
    path: 'manual/draft.md',
    id: 'draft',
    title: 'Unpublished draft',
    url: '/help/draft',
    draft: true,
  },
];
const nav = {
  mode: 'tree',
  descriptor: { id: 'sidebar.cjs', collection: collection.id },
  value: {
    userGuideSidebar: [
      {
        type: 'category',
        label: 'Getting started',
        items: [{ type: 'doc', id: 'start', label: 'Introduction' }, 'guide/setup'],
      },
    ],
  },
};
function leaves(tree) {
  return tree.flatMap((node) =>
    node.page ? [node] : (node.children || []).flatMap((n) => leaves([n])),
  );
}
test('page picker follows sidebar labels, preserves sections, and includes pages outside sidebars', () => {
  const tree = buildLinkTree(
    pages,
    [collection, { id: 'pages:default', root: 'web/pages', type: 'pages' }],
    [nav],
  );
  assert.equal(tree[0].label, 'User Guide');
  assert.equal(tree[0].children[0].label, 'Getting started');
  assert.equal(tree[0].children[0].children[0].label, 'Introduction');
  assert.deepEqual(
    leaves(tree)
      .map((n) => n.page.path)
      .sort(),
    pages
      .filter((p) => !p.draft)
      .map((p) => p.path)
      .sort(),
  );
  assert(leaves(tree).some((n) => n.label === 'Home'));
  assert(tree.some((n) => n.label === 'Other Documentation'));
  const open = openLinkBranches(tree, '/install', '/help/');
  assert(open.has(tree[0].children[0].key));
});
test('dynamic and autogenerated sidebars fall back to collection folders without losing pages', () => {
  const sourceTree = buildLinkTree(pages, [collection], [{ ...nav, mode: 'source', value: null }]);
  assert(leaves(sourceTree).some((n) => n.label === 'Installation'));
  assert(sourceTree[0].children.some((n) => n.label === 'Guide'));
  const automatic = buildLinkTree(
    pages,
    [collection],
    [{ ...nav, value: { manualSidebar: [{ type: 'autogenerated', dirName: 'guide' }] } }],
  );
  assert.equal(automatic[0].children[0].page.id, 'guide/setup');
  assert.equal(leaves(automatic).filter((n) => n.page.id === 'guide/setup').length, 1);
  const shorthand = buildLinkTree(
    pages,
    [collection],
    [{ ...nav, value: { manualSidebar: [{ Basics: ['start', 'guide/setup'] }] } }],
  );
  assert.equal(shorthand[0].children[0].label, 'Basics');
});
test('search keeps section context and includes whole matching sections', () => {
  const tree = buildLinkTree(pages, [collection], [nav]);
  const result = filterLinkTree(tree, 'installation');
  assert.equal(result[0].children[0].label, 'Getting started');
  assert.equal(leaves(result).length, 1);
  assert.equal(leaves(filterLinkTree(tree, 'getting started')).length, 2);
  assert.equal(filterLinkTree(tree, 'nothing like this').length, 0);
});
test('chosen URLs are portable across base paths and manual links remain distinct', () => {
  assert.equal(pageTarget(pages[1], '/help/'), '/install');
  assert.equal(pageTarget(pages[3], '/help/'), '/');
  assert.equal(pageTarget({ url: '/help/help/example' }, '/help/'), '/help/example');
  assert.equal(findLinkedPage(pages, '/install#requirements', '/help/').id, 'guide/setup');
  assert.equal(findLinkedPage(pages, '/help/install', '/help/').id, 'guide/setup');
  assert.equal(findLinkedPage(pages, 'https://example.com', '/help/'), null);
  assert.equal(findLinkedPage(pages, '#section', '/help/'), null);
  assert.equal(findLinkedPage(pages, '/draft', '/help/'), null);
  assert.equal(validateLink('https://example.com/a?b=1#c'), '');
  assert.equal(validateLink('/docs/page'), '');
  assert.equal(validateLink('mailto:docs@example.test'), '');
  assert(validateLink('javascript:alert(1)'));
  assert(validateLink('a path'));
  assert(validateLink(''));
});
