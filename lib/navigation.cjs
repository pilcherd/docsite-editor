const { EditorError } = require('./paths.cjs');
const { exportedObject, unwrap } = require('./literals.cjs');
function literal(node) {
  node = unwrap(node);
  if (['StringLiteral', 'NumericLiteral', 'BooleanLiteral'].includes(node.type)) return node.value;
  if (node.type === 'NullLiteral') return null;
  if (node.type === 'ArrayExpression') return node.elements.map(literal);
  if (node.type === 'ObjectExpression')
    return Object.fromEntries(
      node.properties.map((property) => {
        if (property.type !== 'ObjectProperty' || property.computed)
          throw new EditorError(
            400,
            'This navigation uses computed code. Use the source view or a navigation adapter.',
          );
        return [property.key.name || property.key.value, literal(property.value)];
      }),
    );
  throw new EditorError(
    400,
    'This navigation contains executable expressions. Its source is preserved and available in source view.',
  );
}
function parseNavigation(source, filename = 'sidebars.js') {
  if (filename.endsWith('.json'))
    return { value: JSON.parse(source), start: 0, end: source.length };
  const object = exportedObject(source);
  return { value: literal(object), start: object.start, end: object.end };
}
function validateNavigation(value, ids) {
  if (!value || Array.isArray(value) || typeof value !== 'object')
    throw new EditorError(400, 'Sidebars must be an object.');
  function check(items, depth = 0) {
    if (!Array.isArray(items) || depth > 30) throw new EditorError(400, 'Invalid sidebar items.');
    for (const item of items) {
      if (typeof item === 'string') {
        if (!ids.has(item)) throw new EditorError(400, 'Unknown documentation ID: ' + item);
        continue;
      }
      if (!item || typeof item !== 'object') throw new EditorError(400, 'Invalid sidebar item.');
      if (!item.type) {
        for (const [label, children] of Object.entries(item)) {
          if (!label) throw new EditorError(400, 'A section needs a label.');
          check(children, depth + 1);
        }
        continue;
      }
      if (item.type === 'category') {
        if (!item.label?.trim()) throw new EditorError(400, 'A section needs a title.');
        check(item.items, depth + 1);
      } else if (item.type === 'doc') {
        if (!ids.has(item.id)) throw new EditorError(400, 'Unknown documentation ID: ' + item.id);
      } else if (!['autogenerated', 'link', 'html', 'ref'].includes(item.type))
        throw new EditorError(400, 'Unknown sidebar item type.');
    }
  }
  for (const [name, items] of Object.entries(value)) {
    if (!name.trim()) throw new EditorError(400, 'A sidebar needs a name.');
    check(items);
  }
}
function replaceNavigation(source, value, filename) {
  const range = parseNavigation(source, filename);
  return source.slice(0, range.start) + JSON.stringify(value, null, 2) + source.slice(range.end);
}
module.exports = { parseNavigation, validateNavigation, replaceNavigation };
